AETHER_TEST(Assets_LoadImageMissingFileReturnsFalse) {
    ImageData image;
    AETHER_CHECK(!DecodeImageFile("does/not/exist.png", image));
}

AETHER_TEST(Assets_LoadImageDecodesKnownDimensionsAndSolidColor) {
    std::string path = WriteTempPng("aether_test_solid_red.png", kSolidRedPng, sizeof(kSolidRedPng));

    ImageData image;
    AETHER_CHECK(DecodeImageFile(path, image));
    AETHER_CHECK(image.width == 4);
    AETHER_CHECK(image.height == 4);
    AETHER_CHECK(image.pixels.size() == 4u * 4u * 4u);

    for (u32 i = 0; i < image.width * image.height; ++i) {
        const u8* p = &image.pixels[i * 4];
        AETHER_CHECK(p[0] == 255 && p[1] == 0 && p[2] == 0 && p[3] == 255);
    }

    std::filesystem::remove(path);
}

AETHER_TEST(Assets_LoadImageDecodesCornersInRowMajorTopDownOrder) {
    std::string path = WriteTempPng("aether_test_corners.png", kCornersPng, sizeof(kCornersPng));

    ImageData image;
    AETHER_CHECK(DecodeImageFile(path, image));
    AETHER_CHECK(image.width == 2);
    AETHER_CHECK(image.height == 2);

    auto pixel_at = [&](u32 x, u32 y) { return &image.pixels[(y * image.width + x) * 4]; };

    const u8* top_left = pixel_at(0, 0);
    AETHER_CHECK(top_left[0] == 255 && top_left[1] == 0 && top_left[2] == 0);

    const u8* top_right = pixel_at(1, 0);
    AETHER_CHECK(top_right[0] == 0 && top_right[1] == 255 && top_right[2] == 0);

    const u8* bottom_left = pixel_at(0, 1);
    AETHER_CHECK(bottom_left[0] == 0 && bottom_left[1] == 0 && bottom_left[2] == 255);

    const u8* bottom_right = pixel_at(1, 1);
    AETHER_CHECK(bottom_right[0] == 255 && bottom_right[1] == 255 && bottom_right[2] == 0);

    std::filesystem::remove(path);
}
