void SetError(std::string* error, std::string message) {
    if (error != nullptr) {
        *error = std::move(message);
    }
}

bool IsValidProjectName(const std::string& name) {
    if (name.empty() || name.size() > 64 || name == "." || name == "..") {
        return false;
    }
    for (char c : name) {
        const bool ok = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '_' ||
                        c == '-' || c == ' ';
        if (!ok) {
            return false;
        }
    }
    return name.front() != ' ' && name.back() != ' ';
}

// "0.7.2" -> {0, 7}; false if it doesn't start with two dot-separated numbers.
bool ParseMajorMinor(const std::string& version, int& major, int& minor) {
    return std::sscanf(version.c_str(), "%d.%d", &major, &minor) == 2;
}

constexpr const char* kGitIgnore =
    "# Generated by the Aether editor: regenerated on demand, never committed.\n"
    "Saved/\n"
    "Intermediate/\n";

